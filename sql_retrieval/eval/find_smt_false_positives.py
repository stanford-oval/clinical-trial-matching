def copy_disease_categorizer_artifacts(
    *,
    categorizer_mbench_root: Path,
    subcohort_id: str,
    dst_dir: Path,
    overwrite: bool,
    dry_run: bool,
) -> List[Tuple[bool, str, str, str]]:
    out: List[Tuple[bool, str, str, str]] = []
    src_dir = categorizer_mbench_root / "disease_categorized"
    if not src_dir.exists():
        return [(False, "missing_src_dir", str(src_dir), str(dst_dir / "categorizer" / "disease_categorized"))]

    for src in sorted(src_dir.glob(f"{subcohort_id}_b0_a1.*")):
        if not src.is_file():
            continue
        dst = dst_dir / "categorizer" / "disease_categorized" / src.name
        ok, msg = copy_file(src, dst, overwrite=overwrite, dry_run=dry_run)
        out.append((ok, msg, str(src), str(dst)))
    if not out:
        out.append((False, "no_matches", str(src_dir / f"{subcohort_id}_b0_a1.*"), str(dst_dir / "categorizer" / "disease_categorized")))
    return out


def copy_poslit_categorizer_artifacts_for_perfile_json(
    *,
    categorizer_mbench_root: Path,
    per_file_json_name: str,
    dst_dir: Path,
    overwrite: bool,
    dry_run: bool,
) -> List[Tuple[bool, str, str, str]]:
    out: List[Tuple[bool, str, str, str]] = []
    base_dir = categorizer_mbench_root / "positive_literal_categorized" / "positive_literal_categorized"
    if not base_dir.exists():
        return [(False, "missing_src_dir", str(base_dir), str(dst_dir / "categorizer" / "positive_literal_categorized"))]

    buckets = ["findings", "others", "procedures"]
    any_found = False

    for bucket in buckets:
        src_dir = base_dir / bucket
        if not src_dir.exists():
            continue

        pats = [
            f"{per_file_json_name}_*prompt.txt",
            f"{per_file_json_name}_*raw.txt",
        ]
        for pat in pats:
            for src in sorted(src_dir.glob(pat)):
                if not src.is_file():
                    continue
                any_found = True
                dst = dst_dir / "categorizer" / "positive_literal_categorized" / bucket / src.name
                ok, msg = copy_file(src, dst, overwrite=overwrite, dry_run=dry_run)
                out.append((ok, msg, str(src), str(dst)))

    if not any_found:
        out.append((False, "no_matches", f"{base_dir}/{{findings,others,procedures}}/{per_file_json_name}_*(prompt|raw).txt", str(dst_dir / "categorizer" / "positive_literal_categorized")))
    return out


