def load_jsonl_index(path: Path, id_key: str = "_id") -> Dict[str, Dict[str, Any]]:
    out: Dict[str, Dict[str, Any]] = {}
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if not s:
                continue
            try:
                obj = json.loads(s)
            except Exception:
                continue
            if isinstance(obj, dict) and isinstance(obj.get(id_key), str):
                out[obj[id_key]] = obj
    return out


