def _pct_ok(pct: float) -> float:
    try:
        x = float(pct)
    except Exception:
        return 1.0
    if x <= 0:
        return 0.0
    if x >= 100:
        return 1.0
    return x / 100.0


def _stable_hash01(s: str, seed: int) -> float:
    h = hashlib.sha256(f"{seed}::{s}".encode("utf-8")).hexdigest()
    v = int(h[:13], 16)
    return (v % (2**52)) / float(2**52)


